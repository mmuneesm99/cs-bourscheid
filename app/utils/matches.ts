function luxembourgInstant(day: string, clock: string) {
  const [year, month, date] = day.split("-").map(Number)
  const [hour, minute] = clock.split(":").map(Number)
  const desired = Date.UTC(year, month - 1, date, hour, minute)
  const guess = new Date(desired)
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: "Europe/Luxembourg",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23"
  }).formatToParts(guess)
  const read = Object.fromEntries(parts.map((part) => [part.type, part.value]))
  const shown = Date.UTC(Number(read.year), Number(read.month) - 1, Number(read.day), Number(read.hour), Number(read.minute))
  return new Date(guess.getTime() + (desired - shown))
}

export function fixtureEndsAt(match: { kickoff: string; time: string }) {
  if (!match.time) return luxembourgInstant(match.kickoff, "23:59")
  return new Date(luxembourgInstant(match.kickoff, match.time).getTime() + 105 * 60 * 1000)
}

export function remainingFixtures(now = new Date()) {
  return upcomingFixtures.filter((match) => fixtureEndsAt(match).getTime() > now.getTime())
}

export function scoreParts(score: string) {
  const [home, away] = score.split("-").map((part) => Number(part.trim()))
  return { home, away }
}

export function clubOutcome(match: { home: string; away: string; score: string }) {
  const { home, away } = scoreParts(match.score)
  const atHome = match.home === "CS Bourscheid"
  const ours = atHome ? home : away
  const theirs = atHome ? away : home
  const mark = ours > theirs ? "W" : ours < theirs ? "L" : "D"
  return { ours, theirs, mark, side: atHome ? "home" as const : "away" as const }
}

